/**
 * The authored world seeds — the foundational seeding for the WORLD tier of the
 * world/NPC/scenario + personalization architecture (46 §2's world library, 45 §5 §2).
 *
 * Where `scenarioSeeds.ts` authors each cell's canonical SITUATION (what happens) and
 * `facets/` composes entity TEXTURE (46 §2/§7), these seeds author each cell's canonical
 * PLACE — the stage the situation stands on. The scenario seed is the drama; the world seed is
 * the room it happens in: locus, sensory texture, population, and the quiet tension the place
 * itself exerts. Composition can vary who and how (facets, NPCs, modality angles); the world
 * seed guarantees the WHERE is always written at the encounter's altitude.
 *
 * The load-bearing content rule the user ratified: the permutation of [world, NPC, scenario]
 * components must not produce a stage-incoherent simulation — so every seed carries its own
 * cell and the coherence validator (stageCoherence.ts) treats it as load-bearing for that cell.
 * A Red war-yard never hosts an Amber dialogue as its load-bearing ground; ±1-stage texture
 * (an offhand register, the weather) is the only licensed adjacency.
 *
 * Tags name the place's FLAVOUR domains — every tag resolves in the initial tag store (46 §11
 * invariant 4; validated by the audit below and the G27 gate). Stage altitude is NOT carried in
 * tags: tags are preference vocabulary, stages are developmental altitude (44's lens/altitude
 * separation).
 *
 * Authoring provenance: each seed cites the concept-draft module-spec sections it was grounded
 * in (the facet compiler's provenance discipline, 46 §8 — humans audit content back to the
 * corpus).
 */

import type { Line } from '../domain/Line.js';
import type { Stage } from '../domain/Stage.js';
import type { TagId } from '../world/tags/types.js';
import { ALL_LINES } from '../domain/Line.js';
import { ALL_STAGES } from '../domain/Stage.js';

/** One authored world seed — the cell's canonical place. */
export interface WorldSeed {
  /** `world:{line}:{stage}:authored` — the id the library registers it under. */
  readonly id: string;
  readonly line: Line;
  readonly stage: Stage;
  /** The locus in one breath — where the player stands. Stage-coherent prose. */
  readonly place: string;
  /** The sensory/atmospheric register — what the place sounds, smells, and feels like. */
  readonly texture: string;
  /** The population: who and what lives here (rendered into NPCs by composition, 46 §7). */
  readonly population: string;
  /** What the place itself quietly asks of whoever stands in it (never a metric, Veil-safe). */
  readonly tension: string;
  /** Flavour domains — store-resolved tags that bias ranking (45 §5.3), never altitude. */
  readonly tags: readonly TagId[];
  /** Corpus provenance: which concept-draft module-spec sections ground this seed. */
  readonly groundedIn: string;
}

const SEED_IDS = ['somatic', 'willpower', 'emotional', 'intrapersonal', 'cognitive', 'moral', 'interpersonal', 'spiritual'] as const;
type SeedLine = (typeof SEED_IDS)[number];

/** Capitalized line names matching the domain `Line` type. */
const LINE_NAMES: Record<SeedLine, Line> = {
  somatic: 'Somatic',
  willpower: 'Willpower',
  emotional: 'Emotional',
  intrapersonal: 'Intrapersonal',
  cognitive: 'Cognitive',
  moral: 'Moral',
  interpersonal: 'Interpersonal',
  spiritual: 'Spiritual',
};

/** Convenience builder keeping each entry compact and uniformly shaped. */
function wseed(
  line: SeedLine,
  stage: Stage,
  place: string,
  texture: string,
  population: string,
  tension: string,
  tags: readonly TagId[],
  groundedIn: string,
): WorldSeed {
  return {
    id: `world:${LINE_NAMES[line]}:${stage}:authored`,
    line: LINE_NAMES[line],
    stage,
    place,
    texture,
    population,
    tension,
    tags,
    groundedIn,
  };
}

