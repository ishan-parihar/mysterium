/** Stages or lines without a world seed row above are compile errors, not silent gaps. */
export function assertWorldSeedCoverage(): void {
  const have = new Set(WORLD_SEEDS.map((s) => `${s.line}:${s.stage}`));
  const missing: string[] = [];
  for (const line of ALL_LINES) {
    for (const stage of ALL_STAGES) {
      if (!have.has(`${line}:${stage}`)) missing.push(`${line}:${stage}`);
    }
  }
  if (missing.length > 0) {
    throw new Error(`world seeds: missing cells [${missing.join(', ')}] — 64/64 coverage is a compile-time invariant`);
  }
}

assertWorldSeedCoverage();
